    plot(Rx,FT,'b-o')
    grid on

    xlabel('Radius (m)')
    ylabel('Load (N/m)')
    legend('Fn','Ft')

    %% GENERALIZED FORCES

    FN_interp = interp1(Rx,FN,r,'linear','extrap');
    FT_interp = interp1(Rx,FT,r,'linear','extrap');

    for j = 1:length(r)-1

        dr = r(j+1)-r(j);

        x = r(j)/R;

        phif = ...
              0.0622*x^2 ...
            + 1.7254*x^3 ...
            - 3.2452*x^4 ...
            + 4.7131*x^5 ...
            - 2.2555*x^6;

        phie = ...
              0.3627*x^2 ...
            + 2.5337*x^3 ...
            - 3.5772*x^4 ...
            + 2.3760*x^5 ...
            - 0.6952*x^6;

        Qf(i) = Qf(i) + FN_interp(j)*phif*dr;
        Qe(i) = Qe(i) + FT_interp(j)*phie*dr;

    end

end

