%% STRUCTURAL PARAMETERS

R = max(r);
zeta = 0.00477465;

%% ==========================================================
%% MASS MATRIX
%% ==========================================================

Mf = 0;
Me = 0;

for j = 1:length(r)-1

    dr = r(j+1)-r(j);

    x = r(j)/R;

    phif = ...
          0.0622*x^2 ...
        + 1.7254*x^3 ...
        - 3.2452*x^4 ...
        + 4.7131*x^5 ...
        - 2.2555*x^6;

    phie = ...
          0.3627*x^2 ...
        + 2.5337*x^3 ...
        - 3.5772*x^4 ...
        + 2.3760*x^5 ...
        - 0.6952*x^6;

    Mf = Mf + m(j)*phif^2*dr;
    Me = Me + m(j)*phie^2*dr;

end

M = [Mf 0;
     0 Me];

%% ==========================================================
%% STIFFNESS MATRIX
%% ==========================================================

Kf = 0;
Ke = 0;

for j = 1:length(r)-1

    dr = r(j+1)-r(j);

    x = r(j)/R;

    d2phif = ...
       (2*0.0622 ...
      +6*1.7254*x ...
      -12*3.2452*x^2 ...
      +20*4.7131*x^3 ...
      -30*2.2555*x^4)/R^2;

    d2phie = ...
       (2*0.3627 ...
      +6*2.5337*x ...
      -12*3.5772*x^2 ...
      +20*2.3760*x^3 ...
      -30*0.6952*x^4)/R^2;

    Kf = Kf + EI_flap(j)*d2phif^2*dr;
    Ke = Ke + EI_edge(j)*d2phie^2*dr;

end

K = [Kf 0;
     0 Ke];

%% ==========================================================
%% DAMPING MATRIX
%% ==========================================================

Cff = 2*zeta*sqrt(K(1,1)*M(1,1));
Cee = 2*zeta*sqrt(K(2,2)*M(2,2));

C = [Cff 0;
     0 Cee];

%% ==========================================================
%% NATURAL FREQUENCIES
%% ==========================================================

omega_flap = sqrt(K(1,1)/M(1,1));
omega_edge = sqrt(K(2,2)/M(2,2));

f_flap = omega_flap/(2*pi);
f_edge = omega_edge/(2*pi);

fprintf('\nFlap frequency = %.3f Hz\n',f_flap);
fprintf('Edge frequency = %.3f Hz\n',f_edge);

%% STORAGE

