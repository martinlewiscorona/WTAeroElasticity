%% ==========================================================
%% LOOP OVER OPERATING POINTS
%% ==========================================================

for i = 1:length(v0)

    [Rx,FN,FT,P(i)] = BEM(v0(i),omega(i),pitch(i));

    %% LOAD DISTRIBUTIONS

    figure(1)
    plot(Rx,FN,'r-o')
